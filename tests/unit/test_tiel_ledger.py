"""
tests/unit/test_tiel_ledger.py
==============================
Unit Test Suite for Transactional Intent-Execution Ledger (TIEL).
Validates:
  1. Acoustic timestamp context snapshotting.
  2. Two-Phase Commit (2PC) staging and commitment with payload.
  3. Fail-Closed abortion on missing or empty required payload keys.
  4. Execution lifecycle transitions (INITIALIZED -> STAGED -> COMMITTED -> EXECUTED).
  5. Windows Atomic Persistence disk operations.
"""
from pathlib import Path
import pytest

from jarvis.core.tiel_ledger import (
    AcousticContextSnapshot,
    TransactionRecord,
    TransactionStatus,
    TransactionalIntentExecutionLedger,
)


def test_acoustic_snapshot_capture():
    """Validates acoustic snapshot creation with valid timestamp and fields."""
    snapshot = TransactionalIntentExecutionLedger.capture_acoustic_snapshot()

    assert isinstance(snapshot, AcousticContextSnapshot)
    assert snapshot.timestamp_ns > 0
    assert isinstance(snapshot.window_title, str)
    assert isinstance(snapshot.process_name, str)


def test_tiel_two_phase_commit_success():
    """Validates full staging and commit lifecycle when required payload is provided."""
    ledger = TransactionalIntentExecutionLedger()

    # Stage a transaction requiring content synthesis
    tx = ledger.prepare_transaction(
        intent="zalo_send",
        slots={"recipient": "Hưng"},
        required_payload_keys=["message_content"],
    )

    assert tx.status == TransactionStatus.STAGED_WAITING_PAYLOAD
    assert tx.tx_id in ledger.get_active_transactions()[0].tx_id

    # Commit payload generated by cognitive Tier 3
    committed_tx = ledger.commit_payload(
        tx_id=tx.tx_id,
        payload={"message_content": "Báo cáo tiến độ hoàn tất 100%."},
    )

    assert committed_tx.status == TransactionStatus.COMMITTED
    assert committed_tx.payload["message_content"] == "Báo cáo tiến độ hoàn tất 100%."
    assert committed_tx.committed_at_ns is not None

    # Mark as executed on Win32
    exec_tx = ledger.mark_executed(tx.tx_id)
    assert exec_tx.status == TransactionStatus.EXECUTED
    assert exec_tx.executed_at_ns is not None


def test_tiel_fail_closed_abort_on_missing_payload():
    """Validates that a transaction transitions to ABORTED when required keys are missing."""
    ledger = TransactionalIntentExecutionLedger()

    tx = ledger.prepare_transaction(
        intent="email_dispatch",
        slots={"to": "dev@jarvis.ai"},
        required_payload_keys=["subject", "body"],
    )

    # Deliver incomplete payload (missing body)
    aborted_tx = ledger.commit_payload(
        tx_id=tx.tx_id,
        payload={"subject": "Cập nhật quan trọng"},
    )

    assert aborted_tx.status == TransactionStatus.ABORTED
    assert "Missing or empty required payload keys" in str(aborted_tx.error_message)

    # Attempting to execute an aborted transaction must fail
    with pytest.raises(RuntimeError):
        ledger.mark_executed(tx.tx_id)


def test_tiel_direct_commit_without_payload_requirements():
    """Validates that simple reflex commands without dependencies commit immediately."""
    ledger = TransactionalIntentExecutionLedger()

    tx = ledger.prepare_transaction(
        intent="system_volume_mute",
        slots={"level": 0},
        required_payload_keys=(),
    )

    assert tx.status == TransactionStatus.COMMITTED
    assert tx.committed_at_ns is not None


def test_tiel_atomic_disk_persistence(tmp_path: Path):
    """Validates atomic JSON disk persistence and retrieval."""
    persist_file = tmp_path / "ledger" / "transactions.json"
    ledger = TransactionalIntentExecutionLedger(persist_path=persist_file)

    tx = ledger.prepare_transaction(
        intent="open_app",
        slots={"app_name": "notepad"},
    )

    persisted = ledger.save_to_disk()
    assert persisted is True
    assert persist_file.exists()
    assert tx.tx_id in persist_file.read_text(encoding="utf-8")
