@dataclass(frozen=True)
class SpeculativeCandidateBranch:
    """A speculative candidate token path generated by Medusa heads."""
    tokens: tuple[int, ...]
    probabilities: tuple[float, ...]
    branch_id: int


@dataclass(frozen=True)
class SpeculativeVerificationResult:
    """Result of a single-pass tree verification step."""
    accepted_tokens: tuple[int, ...]
    rejected_tokens: tuple[int, ...]
    accepted_count: int
    speedup_ratio: float
    verification_latency_ms: float
    is_fully_accepted: bool

    def to_dict(self) -> dict[str, Any]:
        """Converts result to telemetry dictionary."""
        return {
            "accepted_count": self.accepted_count,
            "accepted_tokens": list(self.accepted_tokens),
            "speedup_ratio": self.speedup_ratio,
            "verification_latency_ms": self.verification_latency_ms,
            "is_fully_accepted": self.is_fully_accepted,
        }


class TreeAttentionMask:
    """
    Constructs and manages directed acyclic tree attention masks for single-pass verification.
    """

    @staticmethod
    def create_tree_mask(tree_paths: list[list[int]]) -> np.ndarray:
        """
        Builds a 2D attention mask array where mask[i, j] == 0.0 means token i can attend
        to token j (ancestor or self), and -inf means attention is masked out.

        Args:
            tree_paths: List of candidate token index paths from root.

        Returns:
            np.ndarray: Square 2D float32 attention mask.
        """
        if not tree_paths:
            return np.zeros((0, 0), dtype=np.float32)

        # Flatten unique nodes preserving tree hierarchy
        n_tokens = sum(len(p) for p in tree_paths)
        mask = np.full((n_tokens, n_tokens), -1e9, dtype=np.float32)

        offset = 0
        for path in tree_paths:
            p_len = len(path)
            for i in range(p_len):
                for j in range(i + 1):
                    # Token i can attend to token j (ancestor along this branch)
                    mask[offset + i, offset + j] = 0.0
            offset += p_len

        return mask


class MedusaDraftHead:
    """
    Lightweight Residual MLP Head predicting a future token offset t+k.
    """

    def __init__(
        self,
        hidden_dim: int = 512,
        vocab_size: int = 32000,
        offset_k: int = 1,
        seed: int = 42,
    ) -> None:
        """
        Args:
            hidden_dim: Hidden dimension matching Whisper decoder (512 for Small, 384 for Tiny).
            vocab_size: Token vocabulary size.
            offset_k: Target offset (k=1 for t+1, k=2 for t+2, etc.).
        """
        self.hidden_dim = int(hidden_dim)
        self.vocab_size = int(vocab_size)
        self.offset_k = int(offset_k)

        # Deterministic lightweight weights
        rng = np.random.default_rng(seed + offset_k)
        scale_proj = 1.0 / math.sqrt(self.hidden_dim)
        self.w_proj = (rng.normal(0.0, scale_proj, (self.hidden_dim, self.hidden_dim))).astype(np.float32)
        scale_head = 1.0 / math.sqrt(self.hidden_dim)
        self.w_head = (rng.normal(0.0, scale_head, (self.vocab_size, self.hidden_dim))).astype(np.float32)

    def forward(self, hidden_state: np.ndarray) -> np.ndarray:
        """
        Projects hidden state to vocabulary logits.

        Args:
            hidden_state: 1D float32 array of shape (hidden_dim,).

        Returns:
            logits: 1D float32 array of shape (vocab_size,).
        """
        h = np.asarray(hidden_state, dtype=np.float32).flatten()
        # LayerNorm
        h_mean = float(np.mean(h))
        h_std = float(np.std(h)) + 1e-6
        h_norm = (h - h_mean) / h_std

        # SiLU activation: x * sigmoid(x)
        proj = np.dot(self.w_proj, h_norm)
        silu = proj / (1.0 + np.exp(-np.clip(proj, -20.0, 20.0)))

        # Residual connection + projection to vocab
        res = silu + h_norm
        logits = np.dot(self.w_head, res)
        return logits.astype(np.float32)


class WhisperMedusaSpeculativeDecoder:
    """
    Whisper-Medusa Speculative Acoustic Decoder for Accelerating Speech-to-Text.
    Generates non-autoregressive draft candidate branches and verifies them with
    the base Whisper decoder in single-pass parallel tree evaluations.
    """

    def __init__(
        self,
        num_heads: int = 4,
        hidden_dim: int = 512,
        vocab_size: int = 32000,
        acceptance_threshold: float = 0.50,
    ) -> None:
        """
        Args:
            num_heads: Number of lookahead speculative draft heads (default K=4).
            hidden_dim: Decoder embedding dimension (512 for Whisper Small).
            vocab_size: Whisper vocabulary size (typically 32,000 to 51,865).
            acceptance_threshold: Minimum target model posterior probability to accept draft.
        """
        self.num_heads = max(1, int(num_heads))
        self.hidden_dim = int(hidden_dim)
        self.vocab_size = int(vocab_size)
        self.acceptance_threshold = float(acceptance_threshold)

        self.draft_heads: list[MedusaDraftHead] = [
            MedusaDraftHead(
                hidden_dim=self.hidden_dim,
                vocab_size=self.vocab_size,
                offset_k=k + 1,
                seed=100 + k,
            )
            for k in range(self.num_heads)
        ]

        # Telemetry counters
        self.total_speculated: int = 0
        self.total_accepted: int = 0
        self.total_verification_passes: int = 0

    def generate_draft_candidates(
        self,
        hidden_state: np.ndarray,
        top_k: int = 1,
    ) -> list[int]:
        """
        Generates speculative candidate tokens for offsets t+1, ..., t+K.

        Args:
            hidden_state: Decoder representation vector at current step t.
            top_k: Number of candidates per head (top-1 greedy by default).

        Returns:
            list[int]: Candidate token IDs of length <= num_heads.
        """
        candidates: list[int] = []
        for head in self.draft_heads:
            logits = head.forward(hidden_state)
            token_id = int(np.argmax(logits))
            candidates.append(token_id)
        return candidates

    def verify_candidates(
        self,
        draft_tokens: Sequence[int],
        target_model_eval_fn: Callable[[int, int], tuple[int, float]],
    ) -> SpeculativeVerificationResult:
        """
        Verifies draft tokens in order using the target model's evaluation callback.

        Args:
            draft_tokens: List of speculated token IDs [hat_y_{t+1}, ..., hat_y_{t+K}].
            target_model_eval_fn: Callable taking (step_offset, draft_token) and returning
                                  (target_greedy_token, posterior_prob).

        Returns:
            SpeculativeVerificationResult.
        """
        t0 = time.perf_counter()
        accepted: list[int] = []
        rejected: list[int] = []

        for step_idx, draft_token in enumerate(draft_tokens):
            target_token, prob = target_model_eval_fn(step_idx, draft_token)

            # Accept if draft matches target greedy choice or exceeds acceptance threshold
            if draft_token == target_token or prob >= self.acceptance_threshold:
                accepted.append(draft_token)
            else:
                # Draft failed verification: accept target model's true greedy choice and stop
                rejected.append(draft_token)
                accepted.append(target_token)
                break

        # If all drafts were accepted, add the next base token from target
        is_fully_accepted = (len(accepted) == len(draft_tokens))

        elapsed_ms = (time.perf_counter() - t0) * 1000.0
        acc_count = len(accepted)
        speedup = float(acc_count) / 1.0  # Verification cost is 1 pass

        self.total_speculated += len(draft_tokens)
        self.total_accepted += len(accepted)
        self.total_verification_passes += 1

        return SpeculativeVerificationResult(
            accepted_tokens=tuple(accepted),
            rejected_tokens=tuple(rejected),
            accepted_count=acc_count,
            speedup_ratio=speedup,
            verification_latency_ms=elapsed_ms,
            is_fully_accepted=is_fully_accepted,
        )

    @property
    def mean_acceptance_rate(self) -> float:
        """Calculates global speculative token acceptance rate."""
        if self.total_speculated == 0:
            return 0.0
        return float(self.total_accepted) / float(self.total_speculated)

    @property
    def mean_speedup(self) -> float:
        """Calculates mean acceleration factor per verification pass."""
        if self.total_verification_passes == 0:
            return 1.0
        return float(self.total_accepted) / float(self.total_verification_passes)
